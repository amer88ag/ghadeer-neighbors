-- عروض اليوم وتنظيم الواجهة (إضافة فقط، طُبّق على القاعدة الحية 2026-10-20).
-- النص الكامل المطبّق: جداول ghadeer_offers و ghadeer_offer_reports، والدوال
-- _offers_staff, offers_list, offer_submit, offer_report, staff_list_offers, staff_review_offer,
-- manager_set_home_layout، وتحديث get_app_status لإرجاع home_layout.
create table if not exists public.ghadeer_offers (
  id bigint generated by default as identity primary key,
  title text not null, description text,
  category text not null check (category in ('grocery','electronics','pharmacy','local','other')),
  store text not null, branch text, price_before numeric(10,2), price_after numeric(10,2), link text,
  starts_on date not null default (now() at time zone 'Asia/Riyadh')::date, ends_on date not null,
  status text not null default 'pending' check (status in ('pending','published','rejected','hidden')),
  submitted_by bigint references public.members(id) on delete set null, submitter_name text, review_note text,
  reports integer not null default 0, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists ix_ghadeer_offers_pub on public.ghadeer_offers(status, ends_on);
create table if not exists public.ghadeer_offer_reports (
  offer_id bigint not null references public.ghadeer_offers(id) on delete cascade,
  member_id bigint not null references public.members(id) on delete cascade,
  reason text, created_at timestamptz not null default now(), primary key (offer_id, member_id)
);
alter table public.ghadeer_offers enable row level security;
alter table public.ghadeer_offer_reports enable row level security;
revoke all on public.ghadeer_offers, public.ghadeer_offer_reports from anon, authenticated;
