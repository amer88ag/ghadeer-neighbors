-- جيران حي الغدير بالمحالة — فك الارتباط بجداول المشروع الآخر + سد ثغرات الواجهة الجديدة
-- آمن للتكرار (idempotent). لا يحذف أي جدول أو بيانات.
--
-- 1) استعادة الرقم السري كانت تكتب في account_support_requests و account_security_audit_log
--    (جداول مشروع آخر يشارك قاعدة البيانات). ننقلها إلى جدول خاص بالغدير بنفس توقيعات الدوال،
--    فلا تحتاج الواجهة أي تعديل.
-- 2) (لا تغيير) الإقرار بالشروط يستخدم accept_program_terms ذات المعامل p_pin الموجودة في القاعدة.
-- 3) النسخ الاحتياطي كان يقرأ الجداول مباشرة من المتصفح. نضيف manager_export_backup
--    تتحقق من رقم المدير وتستبعد الأرقام السرية.
-- 4) (لا تغيير) قراءة members مباشرة ممنوعة عن anon في القاعدة الحية أصلًا.
--
-- خطة التراجع (Rollback) في آخر الملف.



-- ---------------------------------------------------------------------------
-- 1) جدول طلبات استعادة الرقم السري الخاص بالغدير
-- ---------------------------------------------------------------------------
create table if not exists public.ghadeer_pin_reset_requests (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.members(id) on delete cascade,
  full_name text not null,
  phone text,
  status text not null default 'open' check (status in ('open','closed','rejected')),
  created_at timestamptz not null default now(),
  closed_at timestamptz
);
create index if not exists idx_ghadeer_pin_reset_open on public.ghadeer_pin_reset_requests(member_id, created_at desc) where status = 'open';
alter table public.ghadeer_pin_reset_requests enable row level security;
revoke all on public.ghadeer_pin_reset_requests from anon, authenticated;

create table if not exists public.ghadeer_security_log (
  id bigint generated by default as identity primary key,
  action text not null,
  member_id bigint,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
alter table public.ghadeer_security_log enable row level security;
revoke all on public.ghadeer_security_log from anon, authenticated;

-- نقل الطلبات المفتوحة الحالية (إن وُجدت) من جدول المشروع الآخر — مرة واحدة فقط.
do $$
begin
  if to_regclass('public.account_support_requests') is not null then
    insert into public.ghadeer_pin_reset_requests(member_id, full_name, phone, status, created_at)
    select r.member_id, r.full_name, r.phone, 'open', r.created_at
    from public.account_support_requests r
    where r.request_type = 'password_reset'
      and r.status in ('open','pending','in_review')
      and r.member_id is not null
      and exists (select 1 from public.members m where m.id = r.member_id)
      and not exists (select 1 from public.ghadeer_pin_reset_requests g where g.member_id = r.member_id and g.created_at = r.created_at);
  end if;
end $$;

-- التحقق من رقم المدير يتم عبر public._manager_pin_ok الموجودة (تتضمن قفل المحاولات).

create or replace function public.request_member_pin_reset(p_member_id bigint, p_name text, p_phone text default null)
returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions','pg_temp'
as $$
declare
  v_member public.members%rowtype;
  v_generic constant text := 'إذا كانت البيانات مطابقة، تم تسجيل طلب الاستعادة للمراجعة.';
begin
  select * into v_member from public.members where id = p_member_id and active = true;
  if not found then return jsonb_build_object('success', true, 'message', v_generic); end if;
  if lower(btrim(coalesce(p_name,''))) <> lower(btrim(v_member.name)) then
    return jsonb_build_object('success', true, 'message', v_generic);
  end if;
  if coalesce(btrim(v_member.phone),'') <> '' and btrim(coalesce(p_phone,'')) <> btrim(v_member.phone) then
    return jsonb_build_object('success', true, 'message', v_generic);
  end if;
  if exists (select 1 from public.ghadeer_pin_reset_requests
             where member_id = v_member.id and status = 'open' and created_at > now() - interval '30 minutes') then
    return jsonb_build_object('success', true, 'message', 'يوجد طلب استعادة مفتوح بالفعل وسيتم مراجعته.');
  end if;
  insert into public.ghadeer_pin_reset_requests(member_id, full_name, phone)
  values (v_member.id, v_member.name, nullif(btrim(p_phone),''));
  insert into public.ghadeer_security_log(action, member_id) values ('member_pin_reset_requested', v_member.id);
  return jsonb_build_object('success', true, 'message', 'تم تسجيل طلب استعادة الرقم السري للمراجعة.');
end;
$$;

create or replace function public.manager_get_pin_reset_requests(p_manager_pin text)
returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions','pg_temp'
as $$
begin
  if not public._manager_pin_ok(p_manager_pin) then
    return jsonb_build_object('success', false, 'message', 'الرقم السري غير صحيح أو الحساب مقفل مؤقتًا');
  end if;
  return coalesce((
    select jsonb_agg(jsonb_build_object('id', r.id, 'member_id', r.member_id, 'full_name', r.full_name,
                                        'phone', r.phone, 'status', r.status, 'created_at', r.created_at)
                     order by r.created_at desc)
    from public.ghadeer_pin_reset_requests r where r.status = 'open'), '[]'::jsonb);
end;
$$;

create or replace function public.manager_reset_member_pin_from_request(p_manager_pin text, p_request_id bigint, p_new_pin text)
returns jsonb
language plpgsql
security definer
set search_path to 'public','extensions','pg_temp'
as $$
declare v_req public.ghadeer_pin_reset_requests%rowtype;
begin
  if not public._manager_pin_ok(p_manager_pin) then
    return jsonb_build_object('success', false, 'message', 'الرقم السري غير صحيح أو الحساب مقفل مؤقتًا');
  end if;
  if p_new_pin is null or btrim(p_new_pin) !~ '^[0-9]{4,12}$' then raise exception 'الرقم السري يجب أن يكون من 4 إلى 12 رقمًا'; end if;
  select * into v_req from public.ghadeer_pin_reset_requests where id = p_request_id and status = 'open' for update;
  if not found then raise exception 'طلب الاستعادة غير موجود أو مغلق'; end if;
  update public.members set pin_hash = extensions.crypt(btrim(p_new_pin), extensions.gen_salt('bf'))
  where id = v_req.member_id and active = true;
  if not found then raise exception 'العضو غير موجود أو غير نشط'; end if;
  update public.ghadeer_pin_reset_requests set status = 'closed', closed_at = now() where id = v_req.id;
  insert into public.ghadeer_security_log(action, member_id, metadata)
  values ('member_pin_reset_by_manager', v_req.member_id, jsonb_build_object('request_id', v_req.id));
  return jsonb_build_object('success', true, 'message', 'تم تغيير الرقم السري وإغلاق طلب الاستعادة.');
end;
$$;

revoke all on function public.request_member_pin_reset(bigint,text,text) from public, anon, authenticated;
grant execute on function public.request_member_pin_reset(bigint,text,text) to anon, authenticated;
revoke all on function public.manager_get_pin_reset_requests(text) from public, anon, authenticated;
grant execute on function public.manager_get_pin_reset_requests(text) to anon, authenticated;
revoke all on function public.manager_reset_member_pin_from_request(text,bigint,text) from public, anon, authenticated;
grant execute on function public.manager_reset_member_pin_from_request(text,bigint,text) to anon, authenticated;

