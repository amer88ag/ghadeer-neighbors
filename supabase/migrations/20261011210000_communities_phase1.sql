-- جيران حي الغدير — المجتمعات الجديدة (المرحلة الأولى): الطلب والاعتماد والعضوية الخاصة.
-- مستخدم يطلب إنشاء مجتمع ← يراجعه المطور (أو مشرف مخوّل بإدارة الأعضاء) ← عند الاعتماد يُنشأ رمز انضمام
-- ← الأعضاء يطلبون الانضمام بالرمز ← صاحب المجتمع يقبل أو يرفض. المطور يستطيع إيقاف أي مجتمع أو إعادته.
-- إضافة فقط؛ لا يغيّر جداول الغدير الحالية. عزل الخدمات لكل مجتمع هو المرحلة الثانية.

create table if not exists public.ghadeer_communities (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  owner_member_id bigint not null references public.members(id),
  status text not null default 'pending' check (status in ('pending','active','rejected','suspended')),
  join_code text unique,
  review_note text,
  reviewed_by text,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create unique index if not exists ux_ghadeer_communities_name on public.ghadeer_communities (lower(trim(name))) where status in ('pending','active','suspended');
create index if not exists idx_ghadeer_communities_owner on public.ghadeer_communities(owner_member_id);
alter table public.ghadeer_communities enable row level security;
revoke all on public.ghadeer_communities from anon, authenticated;

create table if not exists public.ghadeer_community_members (
  community_id bigint not null references public.ghadeer_communities(id) on delete cascade,
  member_id bigint not null references public.members(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','admin','member')),
  status text not null default 'pending' check (status in ('pending','approved','rejected','removed')),
  created_at timestamptz not null default now(),
  decided_at timestamptz,
  primary key (community_id, member_id)
);
create index if not exists idx_ghadeer_community_members_member on public.ghadeer_community_members(member_id);
alter table public.ghadeer_community_members enable row level security;
revoke all on public.ghadeer_community_members from anon, authenticated;

create or replace function public._ghadeer_new_join_code() returns text language sql volatile set search_path to 'public','pg_temp' as $$
  select upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
$$;
revoke all on function public._ghadeer_new_join_code() from public, anon, authenticated;

create or replace function public.community_request_create(p_member_id bigint, p_pin text, p_name text, p_description text)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
declare v_id bigint; v_name text := left(trim(coalesce(p_name, '')), 80);
begin
  if not public.member_auth_ok(p_member_id, p_pin) then return jsonb_build_object('success', false, 'message', 'بيانات الدخول غير صحيحة'); end if;
  if length(v_name) < 3 then return jsonb_build_object('success', false, 'message', 'اكتب اسم المجتمع (3 أحرف على الأقل)'); end if;
  if exists (select 1 from public.ghadeer_communities where owner_member_id = p_member_id and status = 'pending') then
    return jsonb_build_object('success', false, 'message', 'لديك طلب قيد المراجعة بالفعل'); end if;
  if (select count(*) from public.ghadeer_communities where owner_member_id = p_member_id and status in ('active','suspended')) >= 3 then
    return jsonb_build_object('success', false, 'message', 'الحد الأقصى ثلاثة مجتمعات لكل عضو'); end if;
  if exists (select 1 from public.ghadeer_communities where lower(trim(name)) = lower(v_name) and status in ('pending','active','suspended')) or v_name like '%الغدير%' then
    return jsonb_build_object('success', false, 'message', 'الاسم مستخدم، اختر اسمًا آخر'); end if;
  insert into public.ghadeer_communities(name, description, owner_member_id) values (v_name, nullif(left(trim(coalesce(p_description, '')), 1000), ''), p_member_id) returning id into v_id;
  insert into public.ghadeer_community_members(community_id, member_id, role, status, decided_at) values (v_id, p_member_id, 'owner', 'approved', now());
  insert into public.ghadeer_security_log(action, member_id, metadata) values ('community_requested', p_member_id, jsonb_build_object('community_id', v_id));
  return jsonb_build_object('success', true, 'id', v_id, 'message', 'تم إرسال طلب المجتمع للمراجعة');
end; $$;

create or replace function public.community_my_list(p_member_id bigint, p_pin text)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
begin
  if not public.member_auth_ok(p_member_id, p_pin) then return jsonb_build_object('success', false, 'message', 'بيانات الدخول غير صحيحة'); end if;
  return coalesce((select jsonb_agg(jsonb_build_object(
      'id', c.id, 'name', c.name, 'description', c.description, 'status', c.status, 'review_note', c.review_note,
      'my_role', cm.role, 'my_status', cm.status, 'owner_name', o.name,
      'join_code', case when cm.role in ('owner','admin') and c.status = 'active' then c.join_code end,
      'members_count', (select count(*) from public.ghadeer_community_members x where x.community_id = c.id and x.status = 'approved'),
      'pending_count', case when cm.role in ('owner','admin') then (select count(*) from public.ghadeer_community_members x where x.community_id = c.id and x.status = 'pending') end,
      'created_at', c.created_at) order by c.created_at desc)
    from public.ghadeer_community_members cm join public.ghadeer_communities c on c.id = cm.community_id join public.members o on o.id = c.owner_member_id
    where cm.member_id = p_member_id and cm.status <> 'removed'), '[]'::jsonb);
end; $$;

create or replace function public.community_join_by_code(p_member_id bigint, p_pin text, p_code text)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
declare c public.ghadeer_communities%rowtype; cur text;
begin
  if not public.member_auth_ok(p_member_id, p_pin) then return jsonb_build_object('success', false, 'message', 'بيانات الدخول غير صحيحة'); end if;
  select * into c from public.ghadeer_communities where join_code = upper(trim(coalesce(p_code, ''))) and status = 'active';
  if not found then return jsonb_build_object('success', false, 'message', 'رمز الانضمام غير صحيح'); end if;
  select status into cur from public.ghadeer_community_members where community_id = c.id and member_id = p_member_id;
  if cur = 'approved' then return jsonb_build_object('success', false, 'message', 'أنت عضو في هذا المجتمع'); end if;
  if cur = 'pending' then return jsonb_build_object('success', false, 'message', 'طلبك قيد المراجعة لدى صاحب المجتمع'); end if;
  insert into public.ghadeer_community_members(community_id, member_id, role, status) values (c.id, p_member_id, 'member', 'pending')
  on conflict (community_id, member_id) do update set status = 'pending', role = 'member', created_at = now(), decided_at = null;
  return jsonb_build_object('success', true, 'message', 'تم إرسال طلب الانضمام إلى «' || c.name || '»');
end; $$;

create or replace function public.community_members(p_member_id bigint, p_pin text, p_community_id bigint)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
declare my_role text; my_status text;
begin
  if not public.member_auth_ok(p_member_id, p_pin) then return jsonb_build_object('success', false, 'message', 'بيانات الدخول غير صحيحة'); end if;
  select role, status into my_role, my_status from public.ghadeer_community_members where community_id = p_community_id and member_id = p_member_id;
  if my_status is distinct from 'approved' then return jsonb_build_object('success', false, 'message', 'غير مصرح'); end if;
  return coalesce((select jsonb_agg(jsonb_build_object('member_id', cm.member_id, 'name', m.name, 'role', cm.role, 'status', cm.status, 'created_at', cm.created_at) order by cm.status desc, m.name)
    from public.ghadeer_community_members cm join public.members m on m.id = cm.member_id
    where cm.community_id = p_community_id and (cm.status = 'approved' or (my_role in ('owner','admin') and cm.status = 'pending'))), '[]'::jsonb);
end; $$;

create or replace function public.community_decide_member(p_member_id bigint, p_pin text, p_community_id bigint, p_target_member_id bigint, p_decision text)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
declare my_role text; c_status text; t_role text;
begin
  if not public.member_auth_ok(p_member_id, p_pin) then return jsonb_build_object('success', false, 'message', 'بيانات الدخول غير صحيحة'); end if;
  select status into c_status from public.ghadeer_communities where id = p_community_id;
  if c_status is distinct from 'active' then return jsonb_build_object('success', false, 'message', 'المجتمع غير نشط'); end if;
  select role into my_role from public.ghadeer_community_members where community_id = p_community_id and member_id = p_member_id and status = 'approved';
  if coalesce(my_role, '') not in ('owner','admin') then return jsonb_build_object('success', false, 'message', 'القبول والرفض لصاحب المجتمع ومشرفيه فقط'); end if;
  select role into t_role from public.ghadeer_community_members where community_id = p_community_id and member_id = p_target_member_id;
  if t_role is null then return jsonb_build_object('success', false, 'message', 'العضو غير موجود في المجتمع'); end if;
  if t_role = 'owner' then return jsonb_build_object('success', false, 'message', 'لا يمكن تعديل صاحب المجتمع'); end if;
  if p_decision = 'admin' and my_role <> 'owner' then return jsonb_build_object('success', false, 'message', 'تعيين المشرفين لصاحب المجتمع فقط'); end if;
  update public.ghadeer_community_members set
    status = case p_decision when 'approve' then 'approved' when 'reject' then 'rejected' when 'remove' then 'removed' when 'admin' then 'approved' when 'member' then 'approved' else status end,
    role = case p_decision when 'admin' then 'admin' when 'member' then 'member' else role end,
    decided_at = now()
  where community_id = p_community_id and member_id = p_target_member_id;
  return jsonb_build_object('success', true);
end; $$;

create or replace function public.community_regenerate_code(p_member_id bigint, p_pin text, p_community_id bigint)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
declare v text;
begin
  if not public.member_auth_ok(p_member_id, p_pin) then return jsonb_build_object('success', false, 'message', 'بيانات الدخول غير صحيحة'); end if;
  if not exists (select 1 from public.ghadeer_communities where id = p_community_id and owner_member_id = p_member_id and status = 'active') then
    return jsonb_build_object('success', false, 'message', 'غير مصرح'); end if;
  loop v := public._ghadeer_new_join_code(); exit when not exists (select 1 from public.ghadeer_communities where join_code = v); end loop;
  update public.ghadeer_communities set join_code = v where id = p_community_id;
  return jsonb_build_object('success', true, 'join_code', v);
end; $$;

-- مراجعة المجتمعات: المطور برقمه، أو مشرف مخوّل بإدارة الأعضاء.
create or replace function public._ghadeer_review_community(p_actor text, p_id bigint, p_action text, p_note text)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
declare c public.ghadeer_communities%rowtype; v text;
begin
  select * into c from public.ghadeer_communities where id = p_id for update;
  if not found then return jsonb_build_object('success', false, 'message', 'المجتمع غير موجود'); end if;
  if p_action = 'approve' then
    if c.status <> 'pending' then return jsonb_build_object('success', false, 'message', 'الطلب ليس قيد المراجعة'); end if;
    loop v := public._ghadeer_new_join_code(); exit when not exists (select 1 from public.ghadeer_communities where join_code = v); end loop;
    update public.ghadeer_communities set status = 'active', join_code = v, review_note = nullif(trim(coalesce(p_note, '')), ''), reviewed_by = p_actor, reviewed_at = now() where id = p_id;
  elsif p_action = 'reject' then
    if c.status <> 'pending' then return jsonb_build_object('success', false, 'message', 'الطلب ليس قيد المراجعة'); end if;
    update public.ghadeer_communities set status = 'rejected', review_note = nullif(trim(coalesce(p_note, '')), ''), reviewed_by = p_actor, reviewed_at = now() where id = p_id;
  elsif p_action = 'suspend' then
    update public.ghadeer_communities set status = 'suspended', review_note = coalesce(nullif(trim(coalesce(p_note, '')), ''), review_note), reviewed_by = p_actor, reviewed_at = now() where id = p_id and status = 'active';
  elsif p_action = 'activate' then
    update public.ghadeer_communities set status = 'active', reviewed_by = p_actor, reviewed_at = now() where id = p_id and status = 'suspended';
  else return jsonb_build_object('success', false, 'message', 'إجراء غير صحيح'); end if;
  if not found and p_action in ('suspend','activate') then return jsonb_build_object('success', false, 'message', 'لا يمكن تنفيذ الإجراء على حالة المجتمع الحالية'); end if;
  insert into public.ghadeer_security_log(action, metadata) values ('community_' || p_action, jsonb_build_object('community_id', p_id, 'by', p_actor));
  return jsonb_build_object('success', true);
end; $$;
revoke all on function public._ghadeer_review_community(text,bigint,text,text) from public, anon, authenticated;

create or replace function public.manager_review_community(p_manager_pin text, p_id bigint, p_action text, p_note text)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
begin
  if not public._manager_pin_ok(p_manager_pin) then return jsonb_build_object('success', false, 'message', 'الرقم السري غير صحيح أو الحساب مقفل مؤقتًا'); end if;
  return public._ghadeer_review_community('manager', p_id, p_action, p_note);
end; $$;

create or replace function public.supervisor_review_community(p_member_id bigint, p_pin text, p_id bigint, p_action text, p_note text)
returns jsonb language plpgsql security definer set search_path to 'public','extensions','pg_temp' as $$
begin
  if not public.member_auth_ok(p_member_id, p_pin) or not exists (select 1 from public.member_permissions where member_id = p_member_id and role = 'supervisor' and can_manage_members) then
    return jsonb_build_object('success', false, 'message', 'غير مصرح'); end if;
  return public._ghadeer_review_community('supervisor:' || p_member_id, p_id, p_action, p_note);
end; $$;

create or replace function public._ghadeer_communities_admin_list()
returns jsonb language sql stable security definer set search_path to 'public','pg_temp' as $$
  select coalesce(jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name, 'description', c.description, 'status', c.status, 'owner_name', m.name,
    'join_code', c.join_code, 'review_note', c.review_note, 'reviewed_by', c.reviewed_by, 'created_at', c.created_at,
    'members_count', (select count(*) from public.ghadeer_community_members x where x.community_id = c.id and x.status = 'approved'))
    order by (c.status = 'pending') desc, c.created_at desc), '[]'::jsonb)
  from public.ghadeer_communities c join public.members m on m.id = c.owner_member_id;
$$;
revoke all on function public._ghadeer_communities_admin_list() from public, anon, authenticated;

